import React from 'react';
import type { DataProvenance } from '../types';
import { ShieldAlert, Database, Cpu, HelpCircle, FileSpreadsheet } from 'lucide-react';

interface Props {
  provenance: DataProvenance | string;
  size?: 'sm' | 'md' | 'lg';
  showLabel?: boolean;
}

export const DataProvenanceBadge: React.FC<Props> = ({ provenance, size = 'md', showLabel = true }) => {
  let bg = 'bg-gray-800 text-gray-300 border-gray-700';
  let icon = <HelpCircle className="w-3.5 h-3.5" />;
  let label = provenance;
  let description = 'Unknown provenance';

  switch (provenance) {
    case 'IMPORTED_REPORT':
      bg = 'bg-emerald-950/70 text-emerald-300 border-emerald-500/40 shadow-emerald-950/20';
      icon = <FileSpreadsheet className="w-3.5 h-3.5 text-emerald-400" />;
      label = 'IMPORTED LAB DATA';
      description = 'Directly imported from uPowerful BST / BettaTeQ test binary';
      break;
    case 'SIMULATED':
      bg = 'bg-purple-950/70 text-purple-300 border-purple-500/40 shadow-purple-950/20';
      icon = <Cpu className="w-3.5 h-3.5 text-purple-400" />;
      label = 'SIMULATED MODEL';
      description = 'Generated by software simulation profile';
      break;
    case 'STORED_UNVERIFIED':
      bg = 'bg-amber-950/70 text-amber-300 border-amber-500/40 shadow-amber-950/20';
      icon = <Database className="w-3.5 h-3.5 text-amber-400" />;
      label = 'STORED LOGS';
      description = 'Database record without physical hardware verification';
      break;
    case 'LIVE_HARDWARE':
      bg = 'bg-cyan-950/70 text-cyan-300 border-cyan-500/40 shadow-cyan-950/20';
      icon = <Cpu className="w-3.5 h-3.5 text-cyan-400" />;
      label = 'LIVE HARDWARE';
      description = 'Real-time telemetry from physical BMS';
      break;
    case 'UNAVAILABLE':
    default:
      bg = 'bg-rose-950/70 text-rose-300 border-rose-500/40 shadow-rose-950/20';
      icon = <ShieldAlert className="w-3.5 h-3.5 text-rose-400" />;
      label = 'UNAVAILABLE';
      description = 'Hardware is disconnected and no records found';
      break;
  }

  const sizeClasses = size === 'sm' ? 'px-2 py-0.5 text-xs' : size === 'lg' ? 'px-3.5 py-1.5 text-sm' : 'px-2.5 py-1 text-xs';

  return (
    <span
      className={`inline-flex items-center gap-1.5 font-medium rounded-full border shadow-sm transition-all ${bg} ${sizeClasses}`}
      title={description}
    >
      {icon}
      {showLabel && <span>{label}</span>}
    </span>
  );
};
