def save_upowerful_test(test_data: Dict[str, Any]) -> int:
    """
    Saves parsed uPowerful BST test data into test_sessions and measurements.
    Sets provenance to IMPORTED_REPORT.
    """
    header = test_data.get("header", {})
    summary = test_data.get("summary", {})
    records = test_data.get("records", [])

    source_file = header.get("source_file", "")
    test_name = os.path.basename(source_file) if source_file else "uPowerful_Test"
    procedure_name = header.get("procedure_name", "Unknown")
    channel_no = header.get("channel_no", 1)
    batch_no = header.get("product_batch", "")
    start_time = header.get("start_time") or datetime.now().isoformat()
    end_time = header.get("end_time") or datetime.now().isoformat()

    conn = sqlite3.connect(DB_PATH)
    cursor = conn.cursor()

    # Check if this exact file was already imported
    if source_file:
        cursor.execute("SELECT id FROM test_sessions WHERE source_file = ?", (source_file,))
        row = cursor.fetchone()
        if row:
            session_id = row[0]
            # Update summary fields in case of re-import
            cursor.execute(
                """
                UPDATE test_sessions SET
                    test_name = ?, procedure_name = ?, channel_no = ?, batch_no = ?,
                    total_records = ?, max_voltage = ?, min_voltage = ?, max_current = ?,
                    min_current = ?, capacity_ah = ?, energy_wh = ?, peak_temperature = ?,
                    duration_seconds = ?, provenance = ?, status = 'COMPLETED'
                WHERE id = ?
                """,
                (
                    test_name, procedure_name, channel_no, batch_no,
                    summary.get("total_records", len(records)),
                    summary.get("max_voltage"), summary.get("min_voltage"),
                    summary.get("max_current"), summary.get("min_current"),
                    summary.get("capacity_ah"), summary.get("energy_wh"),
                    summary.get("peak_temperature"), summary.get("duration_seconds"),
                    PROVENANCE_IMPORTED_REPORT, session_id
                )
            )
            # If records already exist, return existing id
            cursor.execute("SELECT COUNT(*) FROM measurements WHERE session_id = ?", (session_id,))
            if cursor.fetchone()[0] > 0:
                conn.commit()
                conn.close()
                return session_id
        else:
            session_id = None
    else:
        session_id = None

    if session_id is None:
        cursor.execute(
            """
            INSERT INTO test_sessions (
                battery_id, start_time, end_time, status, test_name, procedure_name,
                channel_no, batch_no, source_file, provenance, total_records,
                max_voltage, min_voltage, max_current, min_current,
                capacity_ah, energy_wh, peak_temperature, duration_seconds, test_outcome
            ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
            """,
            (
                1, start_time, end_time, "COMPLETED", test_name, procedure_name,
                channel_no, batch_no, source_file, PROVENANCE_IMPORTED_REPORT,
                summary.get("total_records", len(records)),
                summary.get("max_voltage"), summary.get("min_voltage"),
                summary.get("max_current"), summary.get("min_current"),
                summary.get("capacity_ah"), summary.get("energy_wh"),
                summary.get("peak_temperature"), summary.get("duration_seconds"),
                "PASS"
            )
        )
        session_id = cursor.lastrowid

    # Batch insert measurement records
    meas_rows = []
    for r in records:
        meas_rows.append((
            session_id,
            r.get("timestamp", start_time),
            r.get("voltage", 0.0),
            r.get("current", 0.0),
            r.get("temperature", 25.0),
            0.0, # SOC
            False, # is_simulated
            PROVENANCE_IMPORTED_REPORT,
            r.get("step_no", 0),
            r.get("cycle_no", 0),
            r.get("process_type", "UNKNOWN"),
            r.get("relative_time_sec", 0.0),
            r.get("capacity", 0.0),
            r.get("energy", 0.0)
        ))

    if meas_rows:
        cursor.executemany(
            """
            INSERT INTO measurements (
                session_id, timestamp, voltage, current, temperature, soc,
                is_simulated, provenance, step_no, cycle_no, process_type,
                relative_time_sec, capacity, energy
            ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
            """,
            meas_rows
        )

    conn.commit()
    conn.close()
    return session_id


def get_test_sessions_list(search: Optional[str] = None, limit: int = 100) -> List[Dict[str, Any]]:
    """Returns a list of test sessions with summary metrics."""
    conn = sqlite3.connect(DB_PATH)
    conn.row_factory = sqlite3.Row
    cursor = conn.cursor()

    query = """
        SELECT
            id, battery_id, start_time, end_time, status, test_name, procedure_name,
            channel_no, batch_no, source_file, provenance, total_records,
            max_voltage, min_voltage, max_current, min_current,
            capacity_ah, energy_wh, peak_temperature, duration_seconds, test_outcome
        FROM test_sessions
    """
    params = []
    if search:
        query += " WHERE test_name LIKE ? OR procedure_name LIKE ? OR batch_no LIKE ? OR provenance LIKE ?"
        term = f"%{search}%"
        params.extend([term, term, term, term])

    query += " ORDER BY id DESC LIMIT ?"
    params.append(limit)

    cursor.execute(query, params)
    rows = cursor.fetchall()
    conn.close()

    result = []
    for row in rows:
        d = dict(row)
        if not d.get("test_name"):
            d["test_name"] = f"Session #{d['id']}"
        if not d.get("provenance"):
            d["provenance"] = PROVENANCE_STORED_UNVERIFIED
        result.append(d)
    return result


def get_test_session_detail(session_id: int) -> Optional[Dict[str, Any]]:
    """Returns detailed session header and statistics."""
    conn = sqlite3.connect(DB_PATH)
    conn.row_factory = sqlite3.Row
    cursor = conn.cursor()

    cursor.execute("SELECT * FROM test_sessions WHERE id = ?", (session_id,))
    row = cursor.fetchone()
    if not row:
        conn.close()
        return None

    session_dict = dict(row)
    if not session_dict.get("test_name"):
        session_dict["test_name"] = f"Session #{session_dict['id']}"

    # Get measurement count and alerts
    cursor.execute("SELECT COUNT(*) FROM measurements WHERE session_id = ?", (session_id,))
    session_dict["actual_measurement_count"] = cursor.fetchone()[0]

    cursor.execute("SELECT * FROM alerts WHERE session_id = ? ORDER BY timestamp ASC", (session_id,))
    alerts = [dict(a) for a in cursor.fetchall()]
    session_dict["alerts"] = alerts

    conn.close()
    return session_dict


def get_test_measurements_list(session_id: int, max_points: int = 500) -> List[Dict[str, Any]]:
    """Returns measurements downsampled to at most max_points for smooth frontend chart rendering."""
    conn = sqlite3.connect(DB_PATH)
    conn.row_factory = sqlite3.Row
    cursor = conn.cursor()

    cursor.execute("SELECT COUNT(*) FROM measurements WHERE session_id = ?", (session_id,))
    total = cursor.fetchone()[0]

    if total == 0:
        conn.close()
        return []

    # Downsample evenly if records exceed max_points
    stride = max(1, total // max_points) if total > max_points else 1

    cursor.execute(
        f"""
        SELECT id, session_id, timestamp, voltage, current, temperature, soc,
               is_simulated, provenance, step_no, cycle_no, process_type,
               relative_time_sec, capacity, energy
        FROM measurements
        WHERE session_id = ? AND (rowid % {stride} = 0)
        ORDER BY timestamp ASC
        LIMIT ?
        """,
        (session_id, max_points + 50)
    )
    rows = cursor.fetchall()
    conn.close()

    return [dict(r) for r in rows]


def get_pack_summary() -> Dict[str, Any]:
    """Returns latest telemetry, pack specifications, and current status."""
    latest = get_latest_measurement_record()
    conn = sqlite3.connect(DB_PATH)
    conn.row_factory = sqlite3.Row
    cursor = conn.cursor()

    cursor.execute("SELECT * FROM batteries LIMIT 1")
    bat = cursor.fetchone()
    conn.close()

    bat_dict = dict(bat) if bat else {
        "name": "Default EV Pack",
        "nominal_voltage": 400.0,
        "capacity_ah": 100.0,
        "chemistry": "Li-Ion"
    }

    return {
        "pack": bat_dict,
        "latest_telemetry": latest,
        "hardware_status": "DISCONNECTED",
        "active_mode": "MOCK_SIMULATOR"
    }

