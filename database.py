def get_latest_measurement_record() -> Optional[Dict[str, Any]]:
    """Returns the most recent measurement as a dict with provenance and timestamp."""
    conn = sqlite3.connect(DB_PATH)
    cursor = conn.cursor()
    cursor.execute(
        "SELECT id, session_id, timestamp, voltage, current, temperature, soc, is_simulated, provenance "
        "FROM measurements ORDER BY timestamp DESC LIMIT 1"
    )
    row = cursor.fetchone()
    conn.close()

    if not row:
        return None

    return {
        "id": row[0],
        "session_id": row[1],
        "timestamp": row[2],
        "voltage": row[3],
        "current": row[4],
        "temperature": row[5],
        "soc": row[6],
        "is_simulated": bool(row[7]),
        "provenance": row[8] or (PROVENANCE_SIMULATED if row[7] else PROVENANCE_STORED_UNVERIFIED)
    }


