"""
database.py - SQLite Database operations with strict Data Provenance tracking.

Data Provenance States:
- SIMULATED: Generated by battery simulator.
- STORED_UNVERIFIED: Historical database records without real hardware certification.
- LIVE_HARDWARE: Real-time physical BMS telemetry (never used when hardware is disconnected).
- UNAVAILABLE: Hardware offline or no data recorded.
"""

import sqlite3
import pandas as pd
from datetime import datetime
import os
from typing import Optional, Dict, Any, List

DB_PATH = "ev_battery.db"

# Provenance Constants
PROVENANCE_SIMULATED = "SIMULATED"
PROVENANCE_STORED_UNVERIFIED = "STORED_UNVERIFIED"
PROVENANCE_IMPORTED_REPORT = "IMPORTED_REPORT"
PROVENANCE_LIVE_HARDWARE = "LIVE_HARDWARE"
PROVENANCE_UNAVAILABLE = "UNAVAILABLE"

VALID_PROVENANCES = {
    PROVENANCE_SIMULATED,
    PROVENANCE_STORED_UNVERIFIED,
    PROVENANCE_IMPORTED_REPORT,
    PROVENANCE_LIVE_HARDWARE,
    PROVENANCE_UNAVAILABLE,
}


def init_db():
    conn = sqlite3.connect(DB_PATH)
    cursor = conn.cursor()

    cursor.execute('''
    CREATE TABLE IF NOT EXISTS batteries (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        name TEXT,
        nominal_voltage REAL,
        capacity_ah REAL,
        chemistry TEXT
    )
    ''')

    cursor.execute('''
    CREATE TABLE IF NOT EXISTS test_sessions (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        battery_id INTEGER,
        start_time DATETIME,
        end_time DATETIME,
        status TEXT,
        test_name TEXT,
        procedure_name TEXT,
        channel_no INTEGER,
        batch_no TEXT,
        source_file TEXT,
        provenance TEXT DEFAULT 'STORED_UNVERIFIED',
        total_records INTEGER DEFAULT 0,
        max_voltage REAL,
        min_voltage REAL,
        max_current REAL,
        min_current REAL,
        capacity_ah REAL,
        energy_wh REAL,
        peak_temperature REAL,
        duration_seconds REAL,
        test_outcome TEXT,
        FOREIGN KEY (battery_id) REFERENCES batteries (id)
    )
    ''')

    cursor.execute('''
    CREATE TABLE IF NOT EXISTS measurements (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        session_id INTEGER,
        timestamp DATETIME,
        voltage REAL,
        current REAL,
        temperature REAL,
        soc REAL,
        is_simulated BOOLEAN,
        provenance TEXT DEFAULT 'SIMULATED',
        step_no INTEGER,
        cycle_no INTEGER,
        process_type TEXT,
        relative_time_sec REAL,
        capacity REAL,
        energy REAL,
        FOREIGN KEY (session_id) REFERENCES test_sessions (id)
    )
    ''')

    # Migration: check if columns exist in existing test_sessions table
    cursor.execute("PRAGMA table_info(test_sessions)")
    session_cols = [col[1] for col in cursor.fetchall()]
    new_session_cols = {
        "test_name": "TEXT",
        "procedure_name": "TEXT",
        "channel_no": "INTEGER",
        "batch_no": "TEXT",
        "source_file": "TEXT",
        "provenance": "TEXT DEFAULT 'STORED_UNVERIFIED'",
        "total_records": "INTEGER DEFAULT 0",
        "max_voltage": "REAL",
        "min_voltage": "REAL",
        "max_current": "REAL",
        "min_current": "REAL",
        "capacity_ah": "REAL",
        "energy_wh": "REAL",
        "peak_temperature": "REAL",
        "duration_seconds": "REAL",
        "test_outcome": "TEXT"
    }
    for col_name, col_type in new_session_cols.items():
        if col_name not in session_cols:
            cursor.execute(f"ALTER TABLE test_sessions ADD COLUMN {col_name} {col_type}")

    # Migration: check if columns exist in existing measurements table
    cursor.execute("PRAGMA table_info(measurements)")
    meas_cols = [col[1] for col in cursor.fetchall()]
    new_meas_cols = {
        "provenance": "TEXT DEFAULT 'SIMULATED'",
        "step_no": "INTEGER",
        "cycle_no": "INTEGER",
        "process_type": "TEXT",
        "relative_time_sec": "REAL",
        "capacity": "REAL",
        "energy": "REAL"
    }
    for col_name, col_type in new_meas_cols.items():
        if col_name not in meas_cols:
            cursor.execute(f"ALTER TABLE measurements ADD COLUMN {col_name} {col_type}")

    cursor.execute('''
    CREATE TABLE IF NOT EXISTS alerts (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        session_id INTEGER,
        timestamp DATETIME,
        message TEXT,
        severity TEXT,
        FOREIGN KEY (session_id) REFERENCES test_sessions (id)
    )
    ''')

    # Insert default battery if not exists
    cursor.execute("SELECT COUNT(*) FROM batteries")
    if cursor.fetchone()[0] == 0:
        cursor.execute('''
            INSERT INTO batteries (name, nominal_voltage, capacity_ah, chemistry)
            VALUES ('Default EV Pack', 400.0, 100.0, 'Li-Ion')
        ''')

    conn.commit()
    conn.close()


def create_session(battery_id=1):
    conn = sqlite3.connect(DB_PATH)
    cursor = conn.cursor()
    cursor.execute(
        "INSERT INTO test_sessions (battery_id, start_time, status) VALUES (?, ?, ?)",
        (battery_id, datetime.now().isoformat(), 'RUNNING')
    )
    session_id = cursor.lastrowid
    conn.commit()
    conn.close()
    return session_id


def update_session_status(session_id, status):
    conn = sqlite3.connect(DB_PATH)
    cursor = conn.cursor()
    if status == 'COMPLETED':
        cursor.execute(
            "UPDATE test_sessions SET status = ?, end_time = ? WHERE id = ?",
            (status, datetime.now().isoformat(), session_id)
        )
    else:
        cursor.execute(
            "UPDATE test_sessions SET status = ? WHERE id = ?",
            (status, session_id)
        )
    conn.commit()
    conn.close()


def insert_measurement(
    session_id: int,
    voltage: float,
    current: float,
    temperature: float,
    soc: float,
    is_simulated: bool = True,
    provenance: str = PROVENANCE_SIMULATED
):
    """Inserts a measurement record with explicit provenance tracking."""
    if provenance not in VALID_PROVENANCES:
        provenance = PROVENANCE_STORED_UNVERIFIED

    conn = sqlite3.connect(DB_PATH)
    cursor = conn.cursor()
    cursor.execute(
        "INSERT INTO measurements (session_id, timestamp, voltage, current, temperature, soc, is_simulated, provenance) "
        "VALUES (?, ?, ?, ?, ?, ?, ?, ?)",
        (session_id, datetime.now().isoformat(), voltage, current, temperature, soc, is_simulated, provenance)
    )
    conn.commit()
    conn.close()


