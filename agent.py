def execute_battery_tools(query: str) -> Optional[str]:
    """
    Parses and executes relevant battery tools based on user intent.
    Returns tool result string with unambiguous data provenance.
    """
    q = query.lower()

    match = re.search(r"session\s*#?(\d+)", q)
    session_id = int(match.group(1)) if match else None

    if any(k in q for k in ["upowerful", "bettateq", "sync", "lab software", "data bridge"]):
        return get_upowerful_summary()
    elif any(k in q for k in ["status", "reading", "voltage", "soc", "temperature", "current"]):
        return get_battery_status()
    elif any(k in q for k in ["health", "analyze", "analysis", "abnormal", "anomal"]):
        return analyze_battery_health(session_id)
    elif any(k in q for k in ["report", "pdf", "generate report"]):
        return generate_battery_report(session_id or 1)
    elif any(k in q for k in ["compare", "previous tests", "history", "list tests", "show tests"]):
        return compare_previous_tests()
    elif any(k in q for k in ["hardware", "control", "bms", "workbench", "connected"]):
        return (
            "Hardware Status: DISCONNECTED.\n"
            "- Physical BMS/battery hardware is not connected.\n"
            "- Telemetry Provenance: UNAVAILABLE.\n"
            "- Hardware control commands are locked and disabled for safety."
        )

    return None


def rule_based_fallback(query: str) -> str:
    """Deterministic fallback when all LLMs are unavailable or unconfigured."""
    tool_out = execute_battery_tools(query)
    if tool_out:
        return f"🤖 [Safe Local Fallback Mode - Hardware Disconnected]\n\n{tool_out}"
    return (
        "🤖 [Safe Local Fallback Mode - Hardware Disconnected]\n\n"
        "Operating with simulated telemetry and unverified stored records.\n"
        "Available commands:\n"
        "- `Show battery status` (displays latest SIMULATED readings with timestamp)\n"
        "- `Analyze battery health` (simulation benchmark threshold check)\n"
        "- `Compare previous tests` (historical simulated sessions)\n"
        "- `Generate battery report` (downloadable simulation report)"
    )


def get_agent():
    """Returns router and initial readiness state."""
    providers = router.get_ordered_providers()
    any_configured = any(router.config.is_provider_configured(p) for p in providers)
    return router, any_configured


def chat_with_agent(
    message: str,
    agent_executor: Optional[Any] = None,
    is_llm_ready: Optional[bool] = None,
    conversation_history: Optional[List[Dict[str, str]]] = None
) -> Tuple[str, RouterResult]:
    """
    Routes chat through LLMRouter with automatic fallback.
    Returns (reply_text, router_result).
    """
    active_router = agent_executor if isinstance(agent_executor, LLMRouter) else router

    result = active_router.route_query(
        prompt=message,
        system_prompt=SYSTEM_PROMPT,
        tools_executor=execute_battery_tools,
        conversation_history=conversation_history
    )

    return result.content, result
