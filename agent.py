def get_battery_status() -> str:
    """
    Returns the most recent battery status with explicit data provenance,
    timestamp, and hardware disconnection notice.
    """
    try:
        hw_status = bms_adapter.get_hardware_status()
        latest = get_latest_measurement_record()

        if latest:
            provenance = latest.get("provenance", PROVENANCE_SIMULATED)
            timestamp = latest.get("timestamp", "Unknown")
            voltage = latest.get("voltage", 0.0)
            current = latest.get("current", 0.0)
            temp = latest.get("temperature", 0.0)
            soc = latest.get("soc", 0.0)

            return (
                f"Battery Telemetry Report:\n"
                f"- Hardware Status: {hw_status['status']} (Physical BMS/battery hardware is not connected)\n"
                f"- Data Provenance: {provenance} (SIMULATED DATA - Generated by software test simulator)\n"
                f"- Record Timestamp: {timestamp}\n"
                f"- Voltage: {voltage:.2f} V\n"
                f"- Current: {current:.2f} A\n"
                f"- Cell Temperature: {temp:.2f} °C\n"
                f"- Estimated State of Charge (SOC): {soc:.2f} %\n\n"
                f"⚠️ Provenance Notice: These readings are simulated or stored database logs. "
                f"They are NOT verified hardware measurements, and real-time hardware monitoring is offline."
            )

        return (
            f"Battery Telemetry Report:\n"
            f"- Hardware Status: {hw_status['status']}\n"
            f"- Data Provenance: {PROVENANCE_UNAVAILABLE}\n"
            f"- Telemetry: No measurement records available in the database.\n"
            f"⚠️ Notice: Physical battery hardware is disconnected."
        )
    except Exception as e:
        return f"Database query error: {sanitize_message(str(e))}"


def analyze_battery_health(session_id: Optional[int] = None) -> str:
    """
    Analyzes battery test records for a given session ID or the latest available test session.
    Labels provenance (IMPORTED_REPORT, SIMULATED, etc.) and avoids unsupported universal safety claims.
    """
    try:
        if session_id is None:
            sessions = get_test_sessions_list(limit=1)
            session_id = sessions[0]["id"] if sessions else 1

        detail = get_test_session_detail(session_id)
        df = get_session_measurements(session_id)

        if not detail and df.empty:
            return f"No test session or telemetry data recorded for session #{session_id} to analyze."

        provenance = detail.get("provenance", PROVENANCE_STORED_UNVERIFIED) if detail else PROVENANCE_STORED_UNVERIFIED
        test_name = detail.get("test_name", f"Session #{session_id}") if detail else f"Session #{session_id}"
        proc_name = detail.get("procedure_name", "Unknown") if detail else "Unknown"

        if not df.empty:
            max_t = df['temperature'].max()
            max_v = df['voltage'].max()
            min_v = df['voltage'].min()
            avg_c = df['current'].mean()
            total_pts = len(df)
            if 'is_simulated' in df.columns and df['is_simulated'].any():
                provenance = PROVENANCE_SIMULATED
        else:
            max_t = detail.get("peak_temperature", 0.0)
            max_v = detail.get("max_voltage", 0.0)
            min_v = detail.get("min_voltage", 0.0)
            avg_c = 0.0
            total_pts = detail.get("total_records", 0)

        # Check for configurable test boundary excursions
        excursions = []
        if max_t > 45.0:
            excursions.append(f"Configurable test threshold (45.0 °C) exceeded: Peak {max_t:.1f} °C.")
        if max_v > 430.0:
            excursions.append(f"Configurable high-voltage threshold (430.0 V) reached: Peak {max_v:.1f} V.")
        if min_v < 2.0 and min_v > 0.0:
            excursions.append(f"Low cell voltage detected: Min {min_v:.3f} V.")

        if provenance == PROVENANCE_IMPORTED_REPORT:
            cap_ah = detail.get("capacity_ah", 0.0) or 0.0
            eng_wh = detail.get("energy_wh", 0.0) or 0.0
            dur_s = detail.get("duration_seconds", 0.0) or 0.0
            summary = (
                f"uPowerful BST Laboratory Test Analysis (Session #{session_id}):\n"
                f"- Test File: {test_name}\n"
                f"- Procedure: {proc_name} (Channel: {detail.get('channel_no', 1)})\n"
                f"- Data Provenance: {PROVENANCE_IMPORTED_REPORT} (Imported laboratory test record)\n"
                f"- Hardware Status: DISCONNECTED (Stored test data; live BMS offline)\n"
                f"- Total Records: {total_pts}\n"
                f"- Voltage Range: {min_v:.3f} V to {max_v:.3f} V\n"
                f"- Peak Temperature: {max_t:.1f} °C\n"
                f"- Delivered Capacity: {cap_ah:.4f} Ah ({cap_ah*1000:.1f} mAh)\n"
                f"- Total Energy: {eng_wh:.4f} Wh\n"
                f"- Test Duration: {dur_s:.1f} s\n"
            )
        else:
            summary = (
                f"Session #{session_id} Telemetry Analysis:\n"
                f"- Hardware State: DISCONNECTED (Physical hardware not connected)\n"
                f"- Data Provenance: {provenance} (Synthetic simulation test data)\n"
                f"- Voltage Range: {min_v:.1f} V to {max_v:.1f} V\n"
                f"- Peak Temperature: {max_t:.1f} °C\n"
                f"- Average Current: {avg_c:.1f} A\n"
            )

        if excursions:
            summary += "\n⚠️ Configurable Test Excursions:\n" + "\n".join(f"- {e}" for e in excursions)
        else:
            summary += "\n✅ Telemetry is within expected operational thresholds."

        summary += (
            "\n\n*Notice regarding limits and State of Health (SOH):*\n"
            "- Universal battery safety claims are unsupported; actual operational limits depend on specific "
            "manufacturer cell specifications, chemistry datasheets, and certified BMS firmware limits (currently unverified).\n"
            "- Accurate State of Health (SOH) requires validated electrochemical impedance spectroscopy (EIS) "
            "or reference degradation laboratory curves."
        )
        return summary
    except Exception as e:
        return f"Analysis error: {sanitize_message(str(e))}"


def generate_battery_report(session_id: int = 1) -> str:
    """Triggers generation of a PDF battery report for the given session ID."""
    try:
        from report_generator import generate_pdf_report
        detail = get_test_session_detail(session_id)
        prov = detail.get("provenance", PROVENANCE_SIMULATED) if detail else PROVENANCE_SIMULATED
        battery_info = {
            'name': detail.get('test_name', 'Default EV Pack') if detail else 'Default EV Pack',
            'nominal_voltage': 400.0 if prov == PROVENANCE_SIMULATED else (detail.get('max_voltage', 3.6) if detail else 3.6),
            'capacity_ah': 100.0 if prov == PROVENANCE_SIMULATED else (detail.get('capacity_ah', 2.5) if detail else 2.5),
            'chemistry': 'Li-Ion',
            'provenance': prov,
            'hardware_status': 'DISCONNECTED'
        }
        path = generate_pdf_report(session_id, battery_info)
        return (
            f"Battery report generated successfully at: {path}\n"
            f"- Report Provenance: {prov}\n"
            f"- Hardware Status: DISCONNECTED"
        )
    except Exception as e:
        return f"Report generation failed: {sanitize_message(str(e))}"


def compare_previous_tests() -> str:
    """Compares historical test sessions and summaries with explicit provenance."""
    try:
        sessions = get_test_sessions_list(limit=8)
        if not sessions:
            return "No previous test sessions available for comparison."

        summary_lines = [
            "Historical Test Sessions Overview:",
            "Physical hardware is DISCONNECTED. Records originate from imported lab files or simulator:\n"
        ]
        for s in sessions:
            sid = s['id']
            name = s.get('test_name') or f"Session #{sid}"
            prov = s.get('provenance', PROVENANCE_STORED_UNVERIFIED)
            recs = s.get('total_records', 0)
            max_v = f"{s['max_voltage']:.2f} V" if s.get('max_voltage') is not None else "N/A"
            cap = f"{s['capacity_ah']:.3f} Ah" if s.get('capacity_ah') is not None else "N/A"
            status = s.get('status', 'COMPLETED')
            summary_lines.append(
                f"- Session #{sid} [{prov}]: {name} | Status={status} | Records={recs} | MaxV={max_v} | Cap={cap}"
            )

        return "\n".join(summary_lines)
    except Exception as e:
        return f"Comparison error: {sanitize_message(str(e))}"


